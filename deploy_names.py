# 读取 cooking.html
html_path = BASE + r'\cooking.html'
with open(html_path, 'r', encoding='utf-8') as f:
    html = f.read()

# 替换每个 {no:N, cat:"...", name:"英文名", ...} 中的 name 字段
def replace_name(m):
    no = int(m.group(1))
    cn = NAMES.get(no)
    if cn:
        return m.group(0).replace(m.group(2), cn)
    return m.group(0)

# 匹配 no:数字 后面的 name:"任意内容"
pattern = re.compile(r'\{no:(\d+),\s*cat:"[^"]*",\s*name:"([^"]*)"')
new_html = pattern.sub(replace_name, html)

# 统计替换数量
count = sum(1 for no in NAMES if f'no:{no},' in new_html)
replaced = len(pattern.findall(html))
print(f"找到 {replaced} 个 name 字段")

# 验证几个关键替换
for no in [1, 50, 100, 146, 215, 228]:
    m = re.search(rf'\{{no:{no},\s*cat:"[^"]*",\s*name:"([^"]*)"', new_html)
    if m:
        print(f"  no:{no} → {m.group(1)}")

with open(html_path, 'w', encoding='utf-8') as f:
    f.write(new_html)

print(f"\ncooking.html 已更新！")
